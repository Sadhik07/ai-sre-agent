"""Renders an investigation as a Markdown incident report / postmortem draft."""

from __future__ import annotations

from sre_agent.agent import PLAYBOOK
from sre_agent.models import Investigation, RootCause


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")[:200]


def render_markdown(inv: Investigation) -> str:
    a, f = inv.alert, inv.finding
    cause = f.root_cause if f else RootCause.UNKNOWN
    lines = [
        f"# Incident report: {a.name} on `{a.service}`",
        "",
        f"- **Namespace**: `{a.namespace}`  **Severity**: {a.severity}  "
        f"**Started**: {a.starts_at.isoformat()}",
        f"- **Investigator**: {inv.investigator}  **Tool calls**: {inv.steps}",
        "",
        "## Finding",
        "",
        f"**Root cause**: `{cause.value}`  **Confidence**: {f.confidence:.0%}" if f else "No finding.",
        "",
        f.summary if f else "",
        "",
    ]
    if f and f.evidence_ids:
        lines.append("Supporting evidence: " + ", ".join(f.evidence_ids))
        lines.append("")
    if f and f.alternatives:
        lines.append("Alternatives considered: " + ", ".join(f"{c} ({s})" for c, s in f.alternatives))
        lines.append("")

    lines += ["## Recommended next step", "", PLAYBOOK.get(cause, (None, "Escalate."))[1], ""]
    if inv.actions:
        lines += ["## Actions", "", "| Action | Status | Detail |", "|---|---|---|"]
        for o in inv.actions:
            lines.append(f"| `{o.action.tool}` | **{o.status}** | {_cell(o.detail)} |")
        lines.append("")

    lines += ["## Evidence", "", "| ID | Tool | Summary | Notes |", "|---|---|---|---|"]
    for e in inv.evidence:
        notes = []
        if e.redactions:
            notes.append(f"{e.redactions} value(s) redacted")
        if e.injection_flagged:
            notes.append("contains instruction-like text (treated as data)")
        lines.append(f"| {e.id} | `{e.tool}` | {_cell(e.summary)} | {', '.join(notes)} |")
    lines.append("")

    if inv.blocked_tool_calls:
        lines += ["## Guardrail decisions", ""]
        for b in inv.blocked_tool_calls:
            lines.append(f"- `{b['tool']}` was not run: {b['reason']}")
        lines.append("")

    lines += [
        "## Postmortem draft",
        "",
        "- **Impact**: _fill in from the SLO dashboard (error budget consumed, users affected)_",
        f"- **Trigger**: {f.summary.split(';')[0] if f else '_unknown_'}",
        "- **Detection**: alert `" + a.name + "` fired",
        "- **Action items**: _prevent / detect / mitigate_",
        "",
        "_Generated by sre-agent. Verify every claim against the cited evidence before sharing._",
    ]
    return "\n".join(lines)
